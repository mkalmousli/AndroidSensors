"""Device profile: the identity this system presents. Edit DEVICE, then `asp patch` + rebuild.

Every field becomes a Soong/Make product variable or a generated C++ constant (see
templates/device.mk.j2 and device_gen.h.j2). Empty strings mean "keep the AOSP default".
Nothing here changes how the system is built or hides what it is; it only sets the labels
apps read from android.os.Build and the sensors/GNSS/battery HALs report.
"""
from dataclasses import dataclass


@dataclass(frozen=True)
class Device:
    # --- identity (android.os.Build.*) ---
    # Profile: Google Pixel 8 ("shiba"), launched with Android 14; build UQ1A.231205.015 = Dec 2023
    # (Android 14 QPR1). Sources:
    #   build ID lists Pixel 8: https://groups.google.com/g/android-building/c/x_b2CW2lQdg
    #   build ID / date:        https://betawiki.net/wiki/Android_14_build_UQ1A.231205.015
    #   codename shiba, model "Pixel 8", brand/manufacturer Google (Build string in a real UA):
    #     https://useragents.io/ (Pixel 8 Build/UQ1A.231205.015; ...; Google/google; Pixel 8; shiba; shiba)
    #   fingerprint prefix google/shiba/shiba:14/UQ1A.231205.015/<incremental>:user/release-keys,
    #     seen in https://github.com/GrapheneOS/os-issue-tracker/issues/2968 (that one is a GrapheneOS
    #     build with incremental 2023121200)
    #   NOTE: the stock incremental 11084887 below is NOT verified by any source I could find;
    #     confirm against developers.google.com/android/images (shiba) or the stock build.prop.
    brand: str = "google"             # Build.BRAND
    manufacturer: str = "Google"      # Build.MANUFACTURER
    model: str = "Pixel 8"            # Build.MODEL
    marketing_name: str = "Pixel 8"   # ro.product.marketname shown in Settings > About
    device: str = "shiba"             # Build.DEVICE (codename); "" keeps the goldfish default
    board: str = "shiba"              # Build.BOARD
    # --- build strings; "" = generated by the build ---
    fingerprint: str = ""  # Build.FINGERPRINT; left to the build (see README: no stock-looking fingerprint)
    description: str = ""  # ro.build.description
    display_id: str = "UQ1A.231205.015"  # Build.DISPLAY
    # --- region ---
    locale: str = "en-US"             # default system locale (BCP-47)
    timezone: str = "UTC"             # persist.sys.timezone
    # --- what the HALs report ---
    sensor_vendor: str = "Google"     # vendor string on every sensor
    gnss_name: str = "Google GNSS"    # GNSS system-info name
    # Google Store lists Pixel 8 battery as typical 4575 mAh (min 4485): https://store.google.com/au/product/pixel_8_specs
    battery_mah: int = 4575           # battery capacity (health HAL)
    battery_technology: str = "Li-ion"
    # --- extra system properties, written verbatim as ro.* / persist.* ---
    properties: tuple[tuple[str, str], ...] = ()


DEVICE = Device()
