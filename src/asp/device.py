"""Device profile: the identity this system presents. Edit DEVICE, then `asp patch` + rebuild.

Every field becomes a Soong/Make product variable or a generated C++ constant (see
templates/device.mk.j2 and device_gen.h.j2). Empty strings mean "keep the AOSP default".
Nothing here changes how the system is built or hides what it is; it only sets the labels
apps read from android.os.Build and the sensors/GNSS/battery HALs report.
"""
from dataclasses import dataclass


@dataclass(frozen=True)
class Device:
    # Profile: Google Pixel 8 ("shiba"), launched with Android 14; build UQ1A.231205.015 is the
    # December 2023 release (Android 14 QPR1). Sources:
    #   build ID lists Pixel 8: https://groups.google.com/g/android-building/c/x_b2CW2lQdg
    #   build ID / date:        https://betawiki.net/wiki/Android_14_build_UQ1A.231205.015
    #   codename shiba, model "Pixel 8", brand google / manufacturer Google, as seen in a real
    #     Pixel 8 user agent: https://useragents.io/ (Build/UQ1A.231205.015; Google/google; Pixel 8; shiba)
    #   Pixel 8 battery, typical 4575 mAh (min 4485): https://store.google.com/au/product/pixel_8_specs
    # --- identity (android.os.Build.*) ---
    brand: str = "google"             # Build.BRAND
    manufacturer: str = "Google"      # Build.MANUFACTURER
    model: str = "Pixel 8"            # Build.MODEL
    marketing_name: str = "Pixel 8"   # ro.product.marketname shown in Settings > About
    device: str = "shiba"             # Build.DEVICE (codename); "" keeps the goldfish default
    board: str = "shiba"              # Build.BOARD
    # --- build strings; "" = generated by the build ---
    # Format google/shiba/shiba:14/<build ID>/<incremental>:user/release-keys. The incremental
    # 11084887 is from memory and NOT verified by any source found (a GrapheneOS build of the same
    # ID uses 2023121200, https://github.com/GrapheneOS/os-issue-tracker/issues/2968); check it against
    # `getprop ro.build.fingerprint` on a stock Pixel 8 or https://developers.google.com/android/images.
    fingerprint: str = "google/shiba/shiba:14/UQ1A.231205.015/11084887:user/release-keys"  # Build.FINGERPRINT
    description: str = "shiba-user 14 UQ1A.231205.015 11084887 release-keys"  # ro.build.description
    display_id: str = "UQ1A.231205.015"  # Build.DISPLAY
    # --- region ---
    locale: str = "en-US"             # default system locale (BCP-47)
    timezone: str = "UTC"             # persist.sys.timezone
    # --- what the HALs report ---
    sensor_vendor: str = "Google"     # vendor string on every sensor (placeholder, unsourced)
    gnss_name: str = "Google GNSS"    # GNSS system-info name (placeholder, unsourced)
    battery_mah: int = 4575           # battery capacity (health HAL)
    battery_technology: str = "Li-ion"
    # --- extra system properties, written verbatim as ro.* / persist.* ---
    # Security patch level = the build's date, 2023-12-05 (https://betawiki.net/wiki/Android_14_build_UQ1A.231205.015)
    properties: tuple[tuple[str, str], ...] = (
        ("ro.build.version.security_patch", "2023-12-05"),
    )


DEVICE = Device()
